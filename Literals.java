public class Literals {
    public static void main(String[] args) {

        int i = 100;
        long l = 100l;
        double d = 1.23;       // double literal
        float f = 1.23f;       // float literal (suffix f)
        String s = "hello";    // string literal
        System.out.println(i + " " + l+ " " + d + " " + f + " " + s);
    }
}

