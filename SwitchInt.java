public class SwitchInt {
    public static void main(String[] args) {

          int day=3;
        switch (day){
            case 1:
            System.out.println("mon");
            break;
            case 2:
            System.out.println("Tues");
            break;
            case 3:
            System.out.println("Thrus");
            break;
            case 4:
            System.out.println("friday");
            break;
            default: System.out.println("Other");

        }

    }
}
