public class Typecasting {
    public static void main(String[] args) {
        // implicit typecasting
        int a = 50;
        double b = a;
        System.out.println("b : "+b);

        // explicit typecasting
        float c = 30.90f;
        int d = (int) c;
        System.out.println("d : "+d);

    }
}
